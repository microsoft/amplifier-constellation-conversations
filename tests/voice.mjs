import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {parseVoice,createVoice}=await import('data:text/javascript;base64,'+Buffer.from(await readFile(new URL('../ui/voice.js',import.meta.url))).toString('base64'));
assert.deepEqual(parseVoice('Workshop, send message.'),{action:'send'});
assert.deepEqual(parseVoice('Workshop open conversation My Release'),{action:'open',text:'My Release'});
assert.equal(parseVoice('Please send a note later').action,'dictate');
assert.equal(parseVoice('Workshop reveal password').action,'unknown');
const handlers={},spoken=[],calls=[],statuses=[];
globalThis.document={hidden:false,addEventListener:(e,f)=>handlers[e]=f};
Object.defineProperty(globalThis,'navigator',{value:{language:'en-US'},configurable:true});
let mic;
globalThis.SpeechRecognition=class {constructor(){mic=this;this.starts=0;}start(){this.starts++;this.onstart();}abort(){this.onend?.();}};
globalThis.SpeechSynthesisUtterance=class {constructor(text){this.text=text;}};
globalThis.speechSynthesis={speak:u=>spoken.push(u),cancel:()=>{}};
const voice=createVoice({perform:async x=>{calls.push(x);if(x.action==='send')throw Error('Send failed');},status:s=>statuses.push(s),onEnabled:()=>{},onReadAloud:()=>{}});
voice.enable(true);assert.equal(mic.starts,0,'remote state does not grant microphone consent');
voice.enable(true,true);assert.equal(mic.starts,1);
await voice.transcript('Draft words');assert.equal(calls[0].text,'Draft words');
await assert.rejects(voice.transcript('Workshop send message'),/Send failed/);
voice.readAloud(true);
voice.observe([{id:'old',role:'assistant',status:'complete',text:'old'}],true);assert.equal(spoken.length,0);
voice.observe([{id:'one',role:'assistant',status:'complete',text:'one'},{id:'two',role:'assistant',status:'complete',text:'two'}]);
assert.equal(spoken.length,1);assert.equal(spoken[0].text,'one');spoken[0].onend();assert.equal(spoken[1].text,'two');
voice.close();const starts=mic.starts;spoken[1].onend();assert.equal(mic.starts,starts,'old speech callback cannot reenable microphone');
document.hidden=true;handlers.visibilitychange();assert.equal(voice.state().enabled,false);
console.log('Voice command, consent, failure, read queue and stop checks passed');
